def header(title,slug,W=840):
    """45px pixel-font section strip with blinking cursor and dithered tail"""
    b=[]; s=3; t="^ "+title
    b+=text(t,18,12,s); b.append(brect(18+tw(t,s)+9,12,12,21,"#fff"))
    rnd=random.Random(slug); x0=18+tw(t,s)+48; cols=(W-18-x0)//9
    for i in range(cols):
        p=i/cols
        for j in range(3):
            if rnd.random()<0.15+0.75*p:
                b.append(R(x0+i*9,12+j*8,6,5,rnd.choice(["#333","#555","#888","#fff"] if p>.6 else ["#222","#333","#555"])))
    return b+[R(0,0,W,3,"#fff"),R(0,42,W,3,"#fff"),R(0,0,3,45,"#fff"),R(W-3,0,3,45,"#fff")]
