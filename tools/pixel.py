def R(x,y,w,h,f,extra=""): return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="{f}"{extra}/>'
def bitmap(rows,x,y,s,f):
    o=[]
    for r,row in enumerate(rows):
        c=0
        while c<len(row):
            if row[c]=='#':
                e=c
                while e<len(row) and row[e]=='#': e+=1
                o.append(R(x+c*s,y+r*s,(e-c)*s,s,f)); c=e
            else: c+=1
    return o
def text(t,x,y,s,f="#fff"):
    o=[]
    for i,ch in enumerate(t): o+=bitmap(F[ch].split('|'),x+i*6*s,y,s,f)
    return o
def tw(t,s): return len(t)*6*s-s
def svg(w,h,body,label):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" '
            f'shape-rendering="crispEdges" role="img" aria-label="{label}"><title>{label}</title>'
            +R(0,0,w,h,"#000")+"".join(body)+'</svg>')
def blink(dur="1s"): return f'><animate attributeName="opacity" values="1;1;0;0" keyTimes="0;0.5;0.5;1" dur="{dur}" repeatCount="indefinite"/></rect>'
def brect(x,y,w,h,f,dur="1s"): return R(x,y,w,h,f)[:-2]+blink(dur)

